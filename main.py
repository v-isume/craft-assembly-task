#General functions
import os
import numpy as np
import yaml

#Custom functions
from utils.get_obj_from_eva import get_list_class_name
from utils.get_silhouette_eva_load import get_best_model
from utils.dictionaries import Primitive_scene, tp_gt
from utils.collision_check_new import repositionVisible

#Primitive generation and matching
from utils.mesh_toprimitive import getPrimitive
from utils.symmetry import findSymmetric
from utils.visible import find_visible
from utils.compare_scene import getScene

#1. Load parameters from param file
with open('./cfg/folders_paths.yaml', 'r') as yaml_file:
    config = yaml.safe_load(yaml_file)

input_folder = config['Paths']['input_folder']
output_folder = config['Paths']['output_folder']
template_folder = config['Paths']['template_folder']
scene_prim = config['Paths']['scene_primitives']

os.makedirs(output_folder, exist_ok=True)

#1.1. Load SCENE primitives information
scene_info = np.load(scene_prim, allow_pickle=True)
keys = scene_info.files
sce_dim = scene_info[keys[0]] #dimension
sce_tra = scene_info[keys[1]] #translation
sce_rot = scene_info[keys[2]] #rotation
sce_sha = scene_info[keys[3]] #shape type

scene_primitives = []

for i in range(len(sce_sha)):
    if (sce_sha[i] == 'cylinder1') or (sce_sha[i] == 'cylinder2'):
        sce_sha[i] = 'cylinder'
    if sce_sha[i] == 'cylinder':
        if len(sce_dim[i]) == 2:
            sce_dim[i] = [sce_dim[i][0], sce_dim[i][0], sce_dim[i][1]]
    elif sce_sha[i] == 'box':
        sce_sha[i] = 'cuboid'
    sce_prim = Primitive_scene(sce_dim[i], sce_tra[i], sce_rot[i], sce_sha[i])
    scene_primitives.append(sce_prim)

#2. Load paths of all input images
input_list = [os.path.join(input_folder, x) for x in os.listdir(input_folder) if x.lower().endswith('.jpg')]
input_list.sort() #Sort for convenience

#3. Split input images into mini-batches
batch_size = 10

groups_no = len(input_list) // batch_size
if len(input_list) % batch_size != 0:
    groups_no += 1

input_batches = np.array_split(np.asarray(input_list), groups_no)

img_name_list = []
final_list = []

#4. Prediction loop for batch
for batch in input_batches:
    #4.1. Load EVA02 object detection/segmentation predictions
    mask_list, class_ids, class_names = get_list_class_name(batch)

    #4.2. Run silhouette optimization
    transform_list = []
    models_list = []
    faces_list = []
    for single_img, single_class_name in zip(batch, class_names):
        #Get the path of the combined masks .png generated by EVA02
        img_name = os.path.splitext(os.path.basename(single_img))[0]
        combined_masks_path = os.path.join(output_folder, 'eva_predictions', img_name, 'all_combined.png')
        transform, best_model, visible_faces = get_best_model(single_class_name, template_folder, combined_masks_path)
        transform_list.append(transform)
        models_list.append(best_model)
        faces_list.append(visible_faces)

    #4.3. Generate Primitive Shapes for visible parts of the posed template mesh
    for i in range(len(models_list)):
        single_img = batch[i]
        transform = transform_list[i]
        masks = mask_list[i]
        faces = faces_list[i]
        classes = class_ids[i]
        class_name = class_names[i]

        img_name = os.path.splitext(os.path.basename(single_img))[0]
        model_path = os.path.join(template_folder, class_name, models_list[i] + '_colored.obj')

        list_vtx_idx, list_masks_visible = find_visible(model_path, transform, masks, faces, classes, img_name, output_folder)
        list_clone, x_position_list = findSymmetric(list_vtx_idx, img_name, output_folder)
        primitives = getPrimitive(list_vtx_idx, list_masks_visible, list_clone, img_name, output_folder)
        sce_prim_idx = getScene(primitives, scene_primitives, transform, img_name, output_folder)

        repositionVisible(primitives, img_name, output_folder, class_name)

        final_correspondence = [(primitives[x].part_cat, tp_gt[sce_prim_idx[x]]) for x in range(len(primitives))]

        print("-----------------------------------------")
        print("Current input: ", img_name)
        print("Group of scene primitives: ", final_correspondence)

        img_name_list.append(img_name)
        final_list.append(final_correspondence)

np.savez(os.path.join(output_folder, "all_results"), img_name=np.asanyarray(img_name_list, dtype=object), parts=np.asanyarray(final_list, dtype=object))
